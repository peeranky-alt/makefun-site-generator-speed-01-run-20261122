// Fast drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
// Semantically identical to the reference (vendor/makefun-site in the kit):
// same front matter, template dialect, Markdown subset, slug rule and report,
// byte for byte. Optimisations only change *how* the same values are computed:
//  - slugify results are cached, and pure-ASCII inputs skip NFKD entirely
//    (NFKD is the identity on ASCII, and ASCII has no combining marks);
//  - inline Markdown buffers literal runs and escapes them in bulk instead
//    of escaping one character at a time;
//  - the Markdown lexer dispatches on a line's first characters instead of
//    running six regexes per line;
//  - template rendering appends into one array instead of building a new
//    string per node, and link resolutions are cached per (directory, target);
//  - each source's card is built once and shared between lists and its page.
// No dependencies, no I/O, no clock, no randomness: output is a function of
// the input alone, exactly as the reference.

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const NEED_ESCAPE = /[&<>"']/;
export function escapeHtml(text) {
  return NEED_ESCAPE.test(text) ? text.replace(/[&<>"']/g, (c) => ESCAPES[c]) : text;
}

export const SLUG_MAX = 64;

// Slug cache: slugify is pure, and titles/tags/headings repeat across a site.
const slugCache = new Map();
const NON_ASCII = /[^\x00-\x7F]/;

export function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  let out;
  if (!NON_ASCII.test(text)) {
    // ASCII fast path: NFKD leaves ASCII unchanged and there are no marks.
    out = '';
    let gap = false;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out += '-';
      gap = false;
      out += keep;
    }
    out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
    if (out === '') out = 'untitled';
  } else {
    const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
    out = '';
    let gap = false;
    for (const ch of plain) {
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out += '-';
      gap = false;
      out += keep;
    }
    out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
    if (out === '') out = 'untitled';
  }
  slugCache.set(text, out);
  return out;
}

export function uniqueSlug(slug, taken) {
  if (!taken.has(slug)) {
    taken.add(slug);
    return slug;
  }
  let n = 2;
  let out = `${slug}-2`;
  while (taken.has(out)) out = `${slug}-${++n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

// ---------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];
const LINE = /^([a-z_]+):(?: (.*))?$/;
const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME = /^[a-z0-9-]+$/;
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

export function parseFrontMatter(text) {
  // The front matter is the lines between the opening '---' line and the
  // next line that is exactly '---'. Only that region is split; the body
  // is sliced out whole (the reference splits and re-joins the whole file,
  // which is the same text).
  if (text !== '---' && !text.startsWith('---\n')) return { error: 'no front matter' };
  let closeStart = -1; // index of the closing '---' line's first '-'
  let closeEnd = -1; // index just past the closing line (and its '\n', if any)
  let pos = text.indexOf('\n---', 3);
  while (pos !== -1) {
    const end = pos + 4;
    if (end === text.length || text.charCodeAt(end) === 10) {
      closeStart = pos + 1;
      closeEnd = end === text.length ? end : end + 1;
      break;
    }
    pos = text.indexOf('\n---', end);
  }
  if (closeStart === -1) return { error: 'the front matter is not closed' };
  const fmLines = text.slice(4, closeStart - 1).split('\n');
  const data = {};
  for (let j = 0; j < fmLines.length; j++) {
    const line = fmLines[j];
    if (isBlank(line) || line.charCodeAt(0) === 35) continue; // blank, or comment opening on '#'
    const m = LINE.exec(line);
    if (!m) return { error: `line ${j + 2} is not "key: value"` };
    const key = m[1];
    const raw = (m[2] ?? '').replace(/[ \t]+$/, '');
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body: text.slice(closeEnd) };
}

// ---------------------------------------------------------------- markdown

// `line` with spaces/tabs at either end dropped (same as /^[ \t]+|[ \t]+$/g).
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

function isLangChar(c) {
  return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45;
}

// Fence open: ``` + optional language (A-Z a-z 0-9 _ + -) + spaces/tabs only.
// Returns the language, or null. Fence close: ``` + spaces/tabs only.
function fenceOpen(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  const langStart = i;
  while (i < line.length && isLangChar(line.charCodeAt(i))) i++;
  const lang = line.slice(langStart, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

function fenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

// Heading: 1-6 '#', at least one space/tab, then text (trailing spaces/tabs
// dropped); null when there is no text, or 7+ '#'.
function headingOf(line) {
  if (line.charCodeAt(0) !== 35) return null;
  let n = 0;
  while (n < line.length && line.charCodeAt(n) === 35) n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length) return null;
  const c = line.charCodeAt(n);
  if (c !== 32 && c !== 9) return null;
  const text = trimLine(line.slice(n + 1));
  return text === '' ? null : { depth: n, text };
}

function isHr(line) {
  const c0 = line.charCodeAt(0);
  if (c0 !== 45 && c0 !== 42) return false; // '-' or '*'
  const mark = c0 === 45 ? '---' : '***';
  if (!line.startsWith(mark)) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

// Whether `line` ends a paragraph: blank, fence, heading or thematic break.
function endsParagraph(line) {
  if (line.length === 0) return true;
  const c0 = line.charCodeAt(0);
  if (c0 === 32 || c0 === 9) return isBlank(line);
  if (c0 === 96) return fenceOpen(line) !== null;
  if (c0 === 35) return headingOf(line) !== null;
  if (c0 === 45 || c0 === 42) return isHr(line);
  return false;
}

function lex(src) {
  const lines = src.split('\n');
  const tokens = [];
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (line.length === 0 || (line.charCodeAt(0) === 32 || line.charCodeAt(0) === 9) && isBlank(line)) {
      i++;
      continue;
    }
    const c0 = line.charCodeAt(0);
    if (c0 === 96) {
      const lang = fenceOpen(line);
      if (lang !== null) {
        const body = [];
        i++;
        while (i < n && !fenceClose(lines[i])) body.push(lines[i++]);
        i++;
        tokens.push({ type: 'code', lang, lines: body });
        continue;
      }
    } else if (c0 === 35) {
      const heading = headingOf(line);
      if (heading !== null) {
        tokens.push({ type: 'heading', depth: heading.depth, text: heading.text });
        i++;
        continue;
      }
    } else if (c0 === 45 || c0 === 42) {
      if (isHr(line)) {
        tokens.push({ type: 'hr' });
        i++;
        continue;
      }
    } else if (c0 === 62) { // '>'
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i++];
        l = l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1);
        body.push(l);
      }
      const kept = [];
      for (let k = 0; k < body.length; k++) {
        const t = trimLine(body[k]);
        if (t !== '') kept.push(t);
      }
      tokens.push({ type: 'blockquote', lines: kept });
      continue;
    }
    // List: '- ' / '* ' bullet, or digits + '. ' ordered. Same-kind lines
    // continue it; a line of 2+ spaces then a non-space continues an item.
    let isOrdered = false;
    let start = 1;
    let firstText = null;
    if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) {
      firstText = line.slice(2);
    } else if (c0 >= 48 && c0 <= 57) {
      let d = 0;
      while (d < line.length && line.charCodeAt(d) >= 48 && line.charCodeAt(d) <= 57) d++;
      if (d >= 1 && d <= 9 && line.charCodeAt(d) === 46 && line.charCodeAt(d + 1) === 32) {
        isOrdered = true;
        start = Number(line.slice(0, d));
        firstText = line.slice(d + 2);
      }
    }
    if (firstText !== null) {
      const items = [];
      let cur = [trimLine(firstText)];
      items.push(cur);
      i++;
      while (i < n) {
        const l = lines[i];
        const lc = l.length === 0 ? 0 : l.charCodeAt(0);
        let mText = null;
        if (!isOrdered && (lc === 45 || lc === 42) && l.charCodeAt(1) === 32) mText = l.slice(2);
        else if (isOrdered && lc >= 48 && lc <= 57) {
          let d = 0;
          while (d < l.length && l.charCodeAt(d) >= 48 && l.charCodeAt(d) <= 57) d++;
          if (d >= 1 && d <= 9 && l.charCodeAt(d) === 46 && l.charCodeAt(d + 1) === 32) mText = l.slice(d + 2);
        }
        if (mText !== null) {
          cur = [trimLine(mText)];
          items.push(cur);
          i++;
        } else if (/^ {2,}\S/.test(l)) {
          // Two or more spaces then a non-space continues the item.
          cur.push(trimLine(l));
          i++;
        } else break;
      }
      tokens.push({ type: 'list', ordered: isOrdered, start, items: items.map((parts) => parts.join('\n')) });
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    tokens.push({ type: 'paragraph', text: body.join('\n') });
  }
  return tokens;
}

// Inline: backslash escapes, code spans, strong, emphasis, links. Literal
// runs are buffered and escaped in bulk (identical output to escaping each
// character, since escaping is per-character and context-free).
const ESCAPABLE = new Uint8Array(128);
for (const c of '\\`*_[]()#+-.!>') ESCAPABLE[c.charCodeAt(0)] = 1;

function isEscapable(code) {
  return code < 128 && ESCAPABLE[code] === 1;
}

// First index from `from` where `s` holds `what` outside a backslash escape.
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s.charCodeAt(j) === 92 && j + 1 < s.length && isEscapable(s.charCodeAt(j + 1))) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

// First single * from `from` (one whose run is not **), outside an escape.
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && isEscapable(s.charCodeAt(j + 1))) {
      j++;
      continue;
    }
    if (c !== 42) continue;
    if (s.charCodeAt(j + 1) === 42) {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

export function inline(s, env, out) {
  // `out` is an optional string array to append into; without it a string
  // is returned. Literal text is buffered in `lit` and flushed escaped.
  const top = out === undefined;
  const buf = top ? null : out;
  let acc = '';
  let lit = '';
  const flush = () => {
    if (lit !== '') {
      const e = escapeHtml(lit);
      if (top) acc += e;
      else buf.push(e);
      lit = '';
    }
  };
  const emit = (str) => {
    if (top) acc += str;
    else buf.push(str);
  };
  // Recursive rendering of a span into this same buffer: inline() with an
  // array target appends directly; for the top-level string case we render
  // the span through a temp array and join it.
  const renderInto = (str) => {
    if (top) {
      const tmp = [];
      inline(str, env, tmp);
      emit(tmp.join(''));
    } else {
      inline(str, env, buf);
    }
  };
  let i = 0;
  const re = /[\\`*[]/g;
  while (i < s.length) {
    // Jump over the literal run to the next special character in one
    // C++ regex scan, instead of walking it one character at a time.
    re.lastIndex = i;
    const m = re.exec(s);
    if (m === null) {
      lit += s.slice(i);
      break;
    }
    if (m.index > i) lit += s.slice(i, m.index);
    i = m.index;
    const c = s.charCodeAt(i);
    if (c === 92 && i + 1 < s.length && isEscapable(s.charCodeAt(i + 1))) {
      flush();
      emit(escapeHtml(s[i + 1]));
      i += 2;
      continue;
    }
    if (c === 96) { // '`'
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        flush();
        emit('<code>');
        emit(escapeHtml(s.slice(i + 1, j)));
        emit('</code>');
        i = j + 1;
      } else {
        lit += '`';
        i++;
      }
      continue;
    }
    if (c === 42) { // '*'
      if (s.charCodeAt(i + 1) === 42) {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          flush();
          emit('<strong>');
          renderInto(s.slice(i + 2, j));
          emit('</strong>');
          i = j + 2;
        } else {
          lit += '**';
          i += 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        flush();
        emit('<em>');
        renderInto(s.slice(i + 1, j));
        emit('</em>');
        i = j + 1;
      } else {
        lit += '*';
        i++;
      }
      continue;
    }
    if (c === 91) { // '['
      const k = findUnescaped(s, ']', i + 1);
      const m = k !== -1 && s.charCodeAt(k + 1) === 40 ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        flush();
        emit('<a href="');
        emit(escapeHtml(env.link(target)));
        emit('">');
        renderInto(s.slice(i + 1, k));
        emit('</a>');
        i = m + 1;
        continue;
      }
      lit += '[';
      i++;
      continue;
    }
    lit += s[i];
    i++;
  }
  flush();
  return top ? acc : undefined;
}

export function renderMarkdown(src, env) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  for (const t of lex(src)) {
    switch (t.type) {
      case 'heading': {
        const id = uniqueSlug(slugify(t.text), ids);
        const tmp = [];
        inline(t.text, env, tmp);
        const html = tmp.join('');
        blocks.push(`<h${t.depth} id="${id}">${html}</h${t.depth}>`);
        if (t.depth === 2 || t.depth === 3) toc.push({ level: t.depth, id, html });
        break;
      }
      case 'code': {
        const cls = t.lang === '' ? '' : ` class="language-${escapeHtml(t.lang)}"`;
        let body = '';
        for (let k = 0; k < t.lines.length; k++) body += `${escapeHtml(t.lines[k])}\n`;
        blocks.push(`<pre><code${cls}>${body}</code></pre>`);
        break;
      }
      case 'hr':
        blocks.push('<hr>');
        break;
      case 'blockquote': {
        const tmp = [];
        if (t.lines.length === 0) blocks.push('<blockquote>\n</blockquote>');
        else {
          inline(t.lines.join('\n'), env, tmp);
          blocks.push(`<blockquote>\n<p>${tmp.join('')}</p>\n</blockquote>`);
        }
        break;
      }
      case 'list': {
        const tag = t.ordered ? 'ol' : 'ul';
        const open = t.ordered && t.start !== 1 ? `<ol start="${t.start}">` : `<${tag}>`;
        let inner = '';
        for (let k = 0; k < t.items.length; k++) {
          const tmp = [];
          inline(t.items[k], env, tmp);
          inner += `<li>${tmp.join('')}</li>\n`;
        }
        blocks.push(`${open}\n${inner}</${tag}>`);
        break;
      }
      case 'paragraph': {
        const tmp = [];
        inline(t.text, env, tmp);
        const html = tmp.join('');
        if (excerpt === null) excerpt = html;
        blocks.push(`<p>${html}</p>`);
        break;
      }
    }
  }
  return { html: blocks.map((b) => `${b}\n`).join(''), toc, excerpt: excerpt ?? '' };
}

